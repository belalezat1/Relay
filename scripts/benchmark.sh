#!/usr/bin/env bash
# Relay Phase IX benchmark harness
# Measures tasks/sec for 1 worker and 3 workers, plus a crash-injection duplicate check.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

JAVA_HOME="${JAVA_HOME:-/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home}"
if [[ ! -x "$JAVA_HOME/bin/java" ]]; then
  JAVA_HOME="/opt/homebrew/opt/openjdk@21"
fi
export JAVA_HOME
export PATH="$JAVA_HOME/bin:$PATH"

RESULTS_MD="${RESULTS_MD:-$ROOT/docs/benchmarks.md}"
API_URL="${API_URL:-http://localhost:8080/api}"
TASK_COUNT="${TASK_COUNT:-30}"
COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.yml}"

have_docker=0
if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
  have_docker=1
fi

echo "== Relay benchmarks =="
echo "JAVA_HOME=$JAVA_HOME"
echo "API_URL=$API_URL"
echo "TASK_COUNT=$TASK_COUNT"
echo "docker_available=$have_docker"

measure_worker_mode() {
  local workers="$1"
  local label="$2"
  local start end elapsed rate
  start=$(date +%s)

  for i in $(seq 1 "$TASK_COUNT"); do
    curl -sf -X POST "$API_URL/workflows" \
      -H "Content-Type: application/json" \
      -d "{\"tasks\":[{\"id\":\"t-$i\",\"type\":\"success\"}]}" >/dev/null
  done

  # Wait until all workflows leave PENDING/RUNNING (best-effort polling)
  local remaining=1
  local attempts=0
  while [[ "$remaining" -gt 0 && "$attempts" -lt 120 ]]; do
    sleep 1
    attempts=$((attempts + 1))
    remaining=$(curl -sf "$API_URL/workflows?status=RUNNING&size=100" | grep -o '"id"' | wc -l | tr -d ' ')
    local pending
    pending=$(curl -sf "$API_URL/workflows?status=PENDING&size=100" | grep -o '"id"' | wc -l | tr -d ' ')
    remaining=$((remaining + pending))
  done

  end=$(date +%s)
  elapsed=$((end - start))
  if [[ "$elapsed" -le 0 ]]; then elapsed=1; fi
  rate=$(awk -v t="$TASK_COUNT" -v e="$elapsed" 'BEGIN { printf "%.2f", t / e }')
  echo "| $label | $workers | $TASK_COUNT | ${elapsed}s | ${rate} tasks/sec | measured |" >> "$RESULTS_MD.tmp"
  echo "Measured $label: $rate tasks/sec over ${elapsed}s"
}

crash_duplicate_check() {
  local start_id
  start_id=$(curl -sf -X POST "$API_URL/workflows" \
    -H "Content-Type: application/json" \
    -d '{"tasks":[{"id":"crash","type":"success","idempotencyKey":"bench-crash-1"}]}' | sed -n 's/.*"id":"\([^"]*\)".*/\1/p' | head -1)

  # Second submit with same idempotency key should be rejected while non-terminal, or no-op after success
  local code
  code=$(curl -s -o /dev/null -w "%{http_code}" -X POST "$API_URL/workflows" \
    -H "Content-Type: application/json" \
    -d '{"tasks":[{"id":"crash","type":"success","idempotencyKey":"bench-crash-1"}]}' || true)

  echo "| crash-injection duplicate check | n/a | 1 | n/a | HTTP $code on duplicate key | measured |" >> "$RESULTS_MD.tmp"
  echo "Duplicate idempotency submit HTTP status: $code (workflow=$start_id)"
}

cat > "$RESULTS_MD.tmp" <<EOF
# Relay benchmarks

Generated by \`scripts/benchmark.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ).

| Scenario | Workers | Tasks | Duration | Throughput | Source |
| --- | ---: | ---: | --- | --- | --- |
EOF

if [[ "$have_docker" -eq 1 ]]; then
  echo "Starting Compose stack (postgres + kafka + api)..."
  KAFKA_ENABLED=true docker compose -f "$COMPOSE_FILE" --profile app up -d --build
  echo "Waiting for API..."
  for _ in $(seq 1 90); do
    if curl -sf "$API_URL/actuator/health" >/dev/null 2>&1; then
      break
    fi
    sleep 2
  done
  if ! curl -sf "$API_URL/actuator/health" >/dev/null 2>&1; then
    echo "API failed to become healthy" >&2
    docker compose -f "$COMPOSE_FILE" --profile app logs --tail=80 relay-api >&2 || true
    exit 1
  fi

  measure_worker_mode 1 "kafka 1-worker"
  # Restart with higher concurrency to approximate multi-worker pressure on one JVM
  WORKER_MAX_CONCURRENCY=3 KAFKA_ENABLED=true docker compose -f "$COMPOSE_FILE" --profile app up -d
  sleep 8
  measure_worker_mode 3 "kafka concurrency=3"
  crash_duplicate_check

  echo "" >> "$RESULTS_MD.tmp"
  echo "Notes:" >> "$RESULTS_MD.tmp"
  echo "- Postgres is the source of truth; Kafka carries task dispatch / retry / events via the outbox." >> "$RESULTS_MD.tmp"
  echo "- Concurrent claim tests in \`KafkaReliabilityTest\` / Testcontainers IT cover duplicate side-effect prevention." >> "$RESULTS_MD.tmp"
else
  cat >> "$RESULTS_MD.tmp" <<'EOF'
| kafka 1-worker | 1 | 30 | — | — | run locally |
| kafka concurrency=3 | 3 | 30 | — | — | run locally |
| crash-injection duplicate check | n/a | 1 | — | — | run locally |

Docker was not available when this file was generated. Run locally:

```bash
export JAVA_HOME=/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home
cp .env.example .env
docker compose --profile app up -d --build
./scripts/benchmark.sh
```
EOF
fi

mv "$RESULTS_MD.tmp" "$RESULTS_MD"
echo "Wrote $RESULTS_MD"
